"""Backfill core.page from a Wikimedia XML dump of uk.wikisource instead of
fetching every archive page through the API (~4 days at MediaWiki's rate
limits; the dump takes one download and minutes of local parsing).

Each page's wikitext is turned into the same structure action=parse returns
(links, images, iwlinks, externallinks), so the existing extraction code
(_parse_wiki_templates, _extract_links_from_wiki_parse, classify_page_links)
and the same writer as the live refresh (pipeline.write_page_info) are used.
Whether a linked page exists is answered from the dump itself.

What wikitext can't show is links generated by templates; verify_sample()
measures the difference against the live API on a random sample."""

import bz2
import logging
import os
import random
import re
import xml.etree.ElementTree as ET
from urllib.parse import quote

import mwparserfromhell
import requests

from birddog import pg
from birddog import database_updater as du
from birddog.pipeline import set_watermark, write_page_info, _WATERMARK
from birddog.wiki import WIKI_NAMESPACE_ID, canonicalize_title

_logger = logging.getLogger(__name__)

DUMP_DIR = os.environ.get("BIRDDOG_DUMP_DIR", "/opt/birddog/.cache/dumps")
_DUMP_URL = "https://dumps.wikimedia.org/ukwikisource/{date}/ukwikisource-{date}-pages-articles.xml.bz2"
_USER_AGENT = "BirddogArchiveMonitor/1.0 (+https://github.com/qubusp/birddog-revised)"
_COMMIT_EVERY = 500

_FILE_PREFIXES = {"файл", "file", "зображення", "image"}
_CATEGORY_PREFIXES = {"категорія", "category"}
_COMMONS_PREFIXES = {"c", "commons"}
# {{Архіви/...}} templates turn link_commons, link_commons2.. into Commons
# file links (75k pages); link_FS*/link_arc* are plain URLs and are picked up
# as external links
_COMMONS_PARAM = re.compile(r"^link_commons\d*$")


def latest_dump_date():
    """Newest dated folder whose pages-articles dump finished."""
    import re
    html = requests.get("https://dumps.wikimedia.org/ukwikisource/",
                        headers={"User-Agent": _USER_AGENT}, timeout=60).text
    for date in sorted(set(re.findall(r'href="(\d{8})/"', html)), reverse=True):
        status = requests.get(f"https://dumps.wikimedia.org/ukwikisource/{date}/dumpstatus.json",
                              headers={"User-Agent": _USER_AGENT}, timeout=60)
        if status.ok and status.json()["jobs"].get("articlesdump", {}).get("status") == "done":
            return date
    raise RuntimeError("no finished uk.wikisource dump found")


def download(date):
    """Downloads the pages-articles dump once; returns its local path."""
    os.makedirs(DUMP_DIR, exist_ok=True)
    path = os.path.join(DUMP_DIR, f"ukwikisource-{date}-pages-articles.xml.bz2")
    if os.path.exists(path):
        return path
    tmp = path + ".part"
    with requests.get(_DUMP_URL.format(date=date), headers={"User-Agent": _USER_AGENT},
                      stream=True, timeout=300) as resp:
        resp.raise_for_status()
        with open(tmp, "wb") as f:
            for chunk in resp.iter_content(1 << 20):
                f.write(chunk)
    os.replace(tmp, path)
    return path


def _archive_pages(path):
    """Yields (title, revision_timestamp, wikitext) for non-redirect pages in
    the archive namespace."""
    for _, el in ET.iterparse(bz2.open(path), events=("end",)):
        if not el.tag.endswith("}page"):
            continue
        if el.findtext("{*}ns") == WIKI_NAMESPACE_ID and el.find("{*}redirect") is None:
            yield (el.findtext("{*}title"),
                   el.findtext("{*}revision/{*}timestamp"),
                   el.findtext("{*}revision/{*}text") or "")
        el.clear()


def _resolve(title, target):
    """Resolves subpage-relative link targets ([[/1/]], [[../]])."""
    if target.startswith("../"):
        base = title
        while target.startswith("../"):
            base, target = base.rsplit("/", 1)[0], target[3:]
        return f"{base}/{target}".rstrip("/") if target else base
    if target.startswith("/"):
        return (title + target).rstrip("/")
    return target


def parse_from_wikitext(title, wikitext, existing):
    """Builds the subset of an action=parse response that the extraction code
    reads, from raw wikitext. `existing` is the set of canonical titles in the
    dump, standing in for the API's link-existence lookup."""
    code = mwparserfromhell.parse(wikitext)
    links, images, iwlinks = [], [], []
    for link in code.filter_wikilinks():
        target = str(link.title).strip()
        leading_colon = target.startswith(":")
        target = target.lstrip(":").split("#")[0].strip()
        if not target:
            continue
        prefix, _, rest = target.partition(":")
        prefix_l = prefix.strip().lower()
        if rest and prefix_l in _COMMONS_PREFIXES:
            iwlinks.append({"*": target,
                            "url": "https://commons.wikimedia.org/wiki/"
                                   + quote(rest.strip().replace(" ", "_"), safe=":/")})
        elif rest and prefix_l in _FILE_PREFIXES and not leading_colon:
            images.append(rest.strip().replace(" ", "_"))
        elif rest and prefix_l in _CATEGORY_PREFIXES and not leading_colon:
            continue  # category membership, not a link
        else:
            resolved = _resolve(title, target)
            entry = {"*": resolved}
            if canonicalize_title(resolved) in existing:
                entry["exists"] = ""
            links.append(entry)
    for template in code.filter_templates():
        if not str(template.name).strip().startswith("Архіви"):
            continue
        for param in template.params:
            if _COMMONS_PARAM.match(str(param.name).strip()):
                value = param.value.strip_code().strip()
                if value:
                    iwlinks.append({"*": f"c:{value}",
                                    "url": "https://commons.wikimedia.org/wiki/"
                                           + quote(value.replace(" ", "_"), safe=":/")})
    external = [str(link.url) for link in code.filter_external_links()]
    return {"wikitext": {"*": wikitext}, "links": links, "images": images,
            "iwlinks": iwlinks, "externallinks": external}


def page_info_from_wikitext(title, timestamp, wikitext, existing):
    """Same shape as database_updater._form_page_info_from_title, from the dump."""
    title = canonicalize_title(title)
    parse = parse_from_wikitext(title, wikitext, existing)
    links = du._extract_links_from_wiki_parse(title, parse)
    # parent/children existence comes from the dump, like _verify_page_link_existence
    for item in list(links.get("children") or []) + ([links["parent"]] if links.get("parent") else []):
        item["exists"] = canonicalize_title(item["title"]) in existing
    record = du._parse_wiki_templates(parse)
    record["title"] = du._normalize_title(title)
    record["url"] = du.normalize_url(du.page_url_from_title(title))
    record["domain"] = du.domain_from_url(record["url"])
    record["level"] = du.page_kind(title, links.get("children"))
    label = du.page_label(title)
    record["label"] = label
    record["root_label"] = du.get_root_label(label)
    record["seq_label"] = du.sequential_page_label(label)
    record["timestamp"] = timestamp
    record["availability"] = "linked"
    record["source_type"] = "wiki"
    return {"title": record["title"], "record": record, "links": links}


def load(date=None):
    """Downloads (if needed) and loads one dump into core.page, then rewinds the
    wiki change feed to the dump's newest revision so wiki_changes refreshes
    everything edited since. Returns a summary."""
    date = date or latest_dump_date()
    path = download(date)
    existing = {canonicalize_title(t) for t, _, _ in _archive_pages(path)}
    _logger.info(f"dump_backfill: {date}: {len(existing)} archive pages")

    summary = {"dump": date, "pages": 0, "docs": 0, "errors": 0}
    newest = ""
    conn_ctx = pg.connect()
    conn = conn_ctx.__enter__()
    try:
        cur = conn.cursor()
        for title, ts, text in _archive_pages(path):
            newest = max(newest, ts or "")
            try:
                cur.execute("SAVEPOINT page")
                summary["docs"] += write_page_info(cur, page_info_from_wikitext(title, ts, text, existing))
                cur.execute("RELEASE SAVEPOINT page")
                summary["pages"] += 1
            except Exception as err:   # one bad page must not stop the backfill
                cur.execute("ROLLBACK TO SAVEPOINT page")
                summary["errors"] += 1
                _logger.warning(f"dump_backfill: {title}: {err}")
            if summary["pages"] % _COMMIT_EVERY == 0:
                conn.commit()
                if summary["pages"] % 10000 == 0:
                    _logger.info(f"dump_backfill: {summary}")
        # only move the feed back, never forward past changes not yet read
        cur.execute("SELECT value FROM raw.watermark WHERE source = %s", (_WATERMARK,))
        row = cur.fetchone()
        if row is None or row[0] > newest:
            set_watermark(cur, _WATERMARK, newest)
        summary["watermark"] = newest
        conn.commit()
    finally:
        conn_ctx.__exit__(None, None, None)
    _logger.info(f"dump_backfill: done {summary}")
    return summary


def verify_sample(date=None, size=300, seed=None):
    """Compares a random sample of dump-loaded pages with a live API refresh
    (without writing anything). Returns per-field match rates and examples."""
    date = date or latest_dump_date()
    path = download(date)
    # one pass: collect every title (for link existence) and a uniform
    # random sample of pages (reservoir sampling)
    rng = random.Random(seed)
    existing, reservoir = set(), []
    for i, (title, ts, text) in enumerate(_archive_pages(path)):
        existing.add(canonicalize_title(title))
        if len(reservoir) < size:
            reservoir.append((title, ts, text))
        else:
            j = rng.randint(0, i)
            if j < size:
                reservoir[j] = (title, ts, text)
    dump_info = {canonicalize_title(t): page_info_from_wikitext(t, ts, text, existing)
                 for t, ts, text in reservoir}
    sample = list(dump_info)

    from birddog.pipeline import classify_page_links
    fields = ("native_description", "years", "level", "label")
    stats = {f: 0 for f in fields} | {"children": 0, "documents": 0, "compared": 0, "skipped": 0}
    examples = []
    for title in sample:
        live = du._form_page_info_from_title(title)
        if live.get("error") or live.get("missing"):
            stats["skipped"] += 1   # deleted/moved since the dump, or a transient error
            continue
        dump = dump_info[title]
        stats["compared"] += 1
        diffs = [f for f in fields if (live["record"].get(f) or "") != (dump["record"].get(f) or "")]
        _, live_children, _, live_docs = classify_page_links(title, live["links"])
        _, dump_children, _, dump_docs = classify_page_links(title, dump["links"])
        live_docs = {du.normalize_url(u) for u in live_docs}
        dump_docs = {du.normalize_url(u) for u in dump_docs}
        if set(live_children) != set(dump_children):
            diffs.append("children")
        if live_docs != dump_docs:
            diffs.append("documents")
        for f in fields + ("children", "documents"):
            if f not in diffs:
                stats[f] += 1
        if diffs and len(examples) < 15:
            examples.append({"title": title, "differs": diffs,
                             "docs_only_live": sorted(live_docs - dump_docs)[:3],
                             "docs_only_dump": sorted(dump_docs - live_docs)[:3]})
    n = stats["compared"] or 1
    rates = {f: round(100 * stats[f] / n, 1) for f in fields + ("children", "documents")}
    result = {"dump": date, "compared": stats["compared"], "skipped": stats["skipped"],
              "match_percent": rates, "examples": examples}
    _logger.info(f"dump_backfill.verify: {result}")
    return result
