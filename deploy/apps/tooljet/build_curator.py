def comp(name, ctype, top, left, width, height, properties, styles=None,
         parent=None, validation=None):
    cid = uid("comp:" + name)
    components.append({
        "id": cid,
        "name": name,
        "type": ctype,
        "pageId": PAGE_ID,
        "parent": uid("comp:" + parent) if parent else None,
        "properties": {k: {"value": v} for k, v in properties.items()},
        "general": None,
        "styles": {k: {"value": v} for k, v in (styles or {}).items()},
        "generalStyles": None,
        "displayPreferences": {
            "showOnDesktop": {"value": "{{true}}"},
            "showOnMobile": {"value": "{{false}}"},
        },
        "validation": validation or {},
        "createdAt": TS,
        "updatedAt": TS,
        "layouts": [
            {
                "id": uid(f"layout:{name}:{kind}"),
                "type": kind,
                "top": top,
                "left": left,
                "width": width,
                "height": height,
                "widthPx": None,
                "fillWidth": None,
                "componentId": cid,
                "dimensionUnit": "count",
                "updatedAt": TS,
            }
            for kind in ("desktop", "mobile")
        ],
    })
    return cid


def event(source_kind, source_name, index, ev):
    """source_kind: component | data_query | page"""
    if source_kind == "component":
        sid = uid("comp:" + source_name)
    elif source_kind == "data_query":
        sid = uid("query:" + source_name)
    else:
        sid = PAGE_ID
    events.append({
        "id": uid(f"event:{source_name}:{index}"),
        "name": f"{ev['eventId']} → {ev['actionId']}",
        "index": index,
        "event": ev,
        "sourceId": sid,
        "target": source_kind,
        "appVersionId": VERSION_ID,
        "createdAt": TS,
        "updatedAt": TS,
    })


def run_query(event_id, query):
    return {"eventId": event_id, "actionId": "run-query",
            "queryId": uid("query:" + query), "queryName": query}


def alert(event_id, kind, message):
    return {"eventId": event_id, "actionId": "show-alert",
            "alertType": kind, "message": message}


def col(key, name, size, ctype="string"):
    return {"id": uid("col:" + key + name), "key": key, "name": name,
            "columnType": ctype, "columnSize": size,
            "autogenerated": False, "columnVisibility": True}


