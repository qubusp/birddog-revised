queries = []


def sql_query(name, sql, params):
    queries.append({
        "id": uid("query:" + name),
        "name": name,
        "options": {
            "mode": "sql",
            "query": sql.strip(),
            # Postgres plugin: query_params turns the query into knex
            # named bindings (:name), sent as real bind parameters.
            "query_params": [[k, v] for k, v in params],
            "transformationLanguage": "javascript",
            "enableTransformation": False,
            "runOnPageLoad": False,
            "showSuccessNotification": False,
        },
        "dataSourceId": DS_PG,
        "appVersionId": VERSION_ID,
        "createdAt": TS,
        "updatedAt": TS,
    })


def js_query(name, code):
    queries.append({
        "id": uid("query:" + name),
        "name": name,
        "options": {"code": code.strip(), "hasParamSupport": True,
                    "parameters": [], "runOnPageLoad": False},
        "dataSourceId": DS_RUNJS,
        "appVersionId": VERSION_ID,
        "createdAt": TS,
        "updatedAt": TS,
    })


sql_query("search", """
SELECT kind, id, title, CAST(round(CAST(score AS numeric), 3) AS float8) AS score, snippet, url
FROM core.search(CAST(:q AS text), CAST(:max_rows AS int))
""", [("q", "{{(components.searchInput.value || '').trim()}}"), ("max_rows", "100")])

sql_query("getPage", """
SELECT p.id, p.url, p.title, p.parent_id, p.label, p.level, p.years,
       p.description_en, p.native_description, p.availability, p.comments,
       p.last_birddog_update,
       pp.title AS parent_title,
       (SELECT count(*) FROM core.page c WHERE c.parent_id = p.id) AS children_count
FROM core.page p
LEFT JOIN core.page pp ON pp.id = p.parent_id
WHERE p.id = CAST(:page_id AS bigint)
""", [("page_id", "{{variables.pageId ?? null}}")])

sql_query("getPageDocs", """
SELECT d.id, d.title, d.process_code, d.save_status,
       array_to_string(d.doc_type, ', ') AS doc_type
FROM core.page_document pd
JOIN core.document d ON d.id = pd.document_id
WHERE pd.page_id = CAST(:page_id AS bigint)
ORDER BY d.title, d.id
""", [("page_id", "{{variables.pageId ?? null}}")])

sql_query("getDoc", """
SELECT d.id, d.url, d.title, d.filename, d.mimetype, d.page_count,
       d.availability, d.location_status,
       d.description, d.process_code, array_to_string(d.doc_type, ', ') AS doc_type,
       d.save_status, d.doc_structure, d.doc_scope, d.language, d.processor,
       d.pages_processed, d.when_transcribed, d.comments, d.anomaly, d.anomaly_comment,
       (SELECT string_agg(p.title, chr(10) ORDER BY p.title)
          FROM core.page_document pd JOIN core.page p ON p.id = pd.page_id
         WHERE pd.document_id = d.id) AS owning_pages
FROM core.document d
WHERE d.id = CAST(:doc_id AS bigint)
""", [("doc_id", "{{variables.docId ?? null}}")])

UPDATE_TEXT_FIELDS = [(c, col_) for c, col_, _, _, _ in FIELDS if col_ != "doc_type"]
set_lines = [f"{col_} = NULLIF(CAST(:{col_} AS text), '')" for _, col_ in UPDATE_TEXT_FIELDS]
set_lines.insert(2, "doc_type = (SELECT array_agg(btrim(t.x) ORDER BY t.n)\n"
                    "              FROM unnest(string_to_array(CAST(:doc_type AS text), ',')) WITH ORDINALITY AS t(x, n)\n"
                    "             WHERE btrim(t.x) <> '')")
set_lines.append("anomaly = CAST(:anomaly AS boolean)")
sql_query("saveDoc",
          "UPDATE core.document SET\n    " + ",\n    ".join(set_lines) +
          "\nWHERE id = CAST(:doc_id AS bigint)\nRETURNING id",
          [("doc_id", "{{variables.docId ?? null}}")] +
          [(col_, "{{components." + c + ".value ?? ''}}") for c, col_, _, _, _ in FIELDS] +
          [("anomaly", "{{!!components.docAnomaly.value}}")])

js_query("selectResult", """
const row = components.resultsTable.selectedRow;
if (!row || row.id === undefined || row.id === null) return;
if (row.kind === 'page') {
  await actions.setVariable('pageId', row.id);
  await queries.getPage.run();
  await queries.getPageDocs.run();
} else {
  await actions.setVariable('docId', row.id);
  await queries.getDoc.run();
}
""")

js_query("selectDoc", """
const row = components.pageDocsTable.selectedRow;
if (!row || row.id === undefined || row.id === null) return;
await actions.setVariable('docId', row.id);
await queries.getDoc.run();
""")

js_query("openParent", """
// (`page` is a ToolJet global inside RunJS, so don't use it as a name)
const current = (queries.getPage.data || [])[0];
if (!current || !current.parent_id) return;
await actions.setVariable('pageId', current.parent_id);
await queries.getPage.run();
await queries.getPageDocs.run();
""")

